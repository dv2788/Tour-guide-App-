#!/usr/bin/env python3
"""Printable QR cards for riads, hostels and hotel desks: marketing/cards.html.

One A4 sheet of ten business-size cards (85 x 55 mm) per sample city, each with a QR code to
that city's tour page. Printed at the reception's own printer: nothing to pay.

    pip install segno
    python3 scripts/make-cards.py                      # links to the current address
    SITE_URL=https://heyroamie.com/ python3 scripts/make-cards.py   # after the domain move
"""
import html
import io
import json
import os
import pathlib
import subprocess

import segno

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = os.environ.get('SITE_URL', 'https://dv2788.github.io/Tour-guide-App-/').rstrip('/') + '/'

samples = json.loads(
    subprocess.run(
        ['node', '--input-type=module', '-e', "import { SAMPLES } from './js/samples.js'; console.log(JSON.stringify(SAMPLES))"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
)
# Where most visitors stay: the medina, the old town… ("A free audio walk through …").
THROUGH = {
    'marrakesh': 'the medina of Marrakesh', 'fes': 'the medina of Fez', 'tunis': 'the medina of Tunis',
    'zanzibar': 'Stone Town', 'cartagena': 'the walled city', 'cairo': 'medieval Cairo',
    'barcelona': 'Barcelona', 'rio-de-janeiro': 'Old Rio', 'kinshasa': 'Kinshasa',
}


def qr_symbol(url, sid):
    """The QR code once, as an SVG symbol the ten cards reuse."""
    out = io.BytesIO()
    segno.make(url, error='m').save(out, kind='svg', xmldecl=False, svgns=True, nl=False, border=0, dark='#16181e', svgclass=None, lineclass=None, omitsize=True)
    svg = out.getvalue().decode()
    view = svg.split('viewBox="', 1)[1].split('"', 1)[0]
    inner = svg.split('>', 1)[1].rsplit('</svg>', 1)[0]
    return f'<svg width="0" height="0" style="position:absolute" aria-hidden="true"><symbol id="{sid}" viewBox="{view}">{inner}</symbol></svg>'


def card(sample, url, shown, sid):
    verb = 'drive' if sample['mode'] == 'drive' else 'walk'
    place = THROUGH.get(sample['id'], sample['label'])
    stops = len(sample['stops'])
    # Never earphones at the wheel: the car's speakers instead.
    how = "Scan, play it through the car's speakers, and drive." if verb == 'drive' else 'Scan, put your earphones in, and walk.'
    return f'''<div class="card">
  <div class="text">
    <p class="brand"><img src="icon.svg" alt="">ROAMIE</p>
    <h2>A free audio {verb} through {html.escape(place)}</h2>
    <p class="blurb">{html.escape(sample['blurb'])} · {stops} stops · {sample['km']:g} km</p>
    <p class="how">{how}</p>
    <p class="small">Free · nothing to install · no account<br>{html.escape(shown)}</p>
  </div>
  <div class="qr" role="img" aria-label="QR code to {html.escape(url)}"><svg><use href="#{sid}"/></svg></div>
</div>'''


sheets = []
links = []
for s in sorted(samples, key=lambda x: x['label']):
    url = f"{SITE}tours/{s['id']}/?utm_source=card"
    shown = f"{SITE.split('://', 1)[1]}tours/{s['id']}/"
    sid = f"qr-{s['id']}"
    sheets.append(f'<section class="sheet" id="{s["id"]}" aria-label="{html.escape(s["label"])}">' + qr_symbol(url, sid) + ''.join(card(s, url, shown, sid) for _ in range(10)) + '</section>')
    links.append(f'<a href="#{s["id"]}">{html.escape(s["label"])}</a>')

page = f'''<!doctype html>
<html lang="en">
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>Roamie QR Cards</title>
<link rel="stylesheet" href="../css/fonts.css">
<style>
  /* Generated by scripts/make-cards.py: edit the script, not this file. */
  :root {{ --ink: #16181e; --muted: #6b665c; --gold: #7f5f25; --gold-bright: #c9a55c; --paper: #fffdf8; --bg: #f6f1e8; }}
  * {{ box-sizing: border-box; }}
  body {{ margin: 0; background: var(--bg); color: var(--ink); font: 300 15px/1.5 'Jost', system-ui, sans-serif; }}
  .tools {{ max-width: 210mm; margin: 0 auto; padding: 20px 16px 8px; }}
  .tools h1 {{ font: 500 1.8rem/1.2 'Cormorant Garamond', Georgia, serif; margin: 0 0 6px; }}
  .tools p {{ margin: 0 0 10px; color: var(--muted); }}
  .pick {{ display: flex; flex-wrap: wrap; gap: 6px 14px; margin: 8px 0 4px; }}
  .pick a {{ color: var(--gold); }}
  .sheet {{ display: none; grid-template-columns: repeat(2, 85mm); grid-auto-rows: 55mm; gap: 0; justify-content: center; align-content: start;
    width: 210mm; min-height: 297mm; margin: 12px auto 40px; padding: 10mm 0; background: white; box-shadow: 0 2px 18px rgb(0 0 0 / 12%); }}
  .sheet:target, body:not(:has(.sheet:target)) #marrakesh {{ display: grid; }}
  .card {{ display: grid; grid-template-columns: 1fr 27mm; gap: 3mm; align-items: center; padding: 4.5mm 5mm; background: var(--paper);
    outline: 0.2mm dashed #c8c2b4; outline-offset: -0.1mm; overflow: hidden; }}
  .brand {{ display: flex; align-items: center; gap: 1.6mm; margin: 0; font: 600 2.6mm/1 'Cormorant Garamond', Georgia, serif; letter-spacing: 0.32em; color: var(--gold); }}
  .brand img {{ width: 4.2mm; height: 4.2mm; border-radius: 1mm; }}
  h2 {{ margin: 1.6mm 0 1mm; font: 500 4.3mm/1.08 'Cormorant Garamond', Georgia, serif; }}
  .blurb {{ margin: 0; font-size: 2.35mm; line-height: 1.3; color: var(--muted); }}
  .how {{ margin: 1.4mm 0 0; font-size: 2.5mm; font-weight: 400; }}
  .small {{ margin: 1.2mm 0 0; font-size: 1.95mm; line-height: 1.35; color: var(--muted); word-break: break-all; }}
  .qr svg {{ display: block; width: 27mm; height: 27mm; }}
  @page {{ size: A4; margin: 0; }}
  @media print {{
    body {{ background: white; }}
    .tools {{ display: none; }}
    .sheet {{ margin: 0; box-shadow: none; }}
  }}
</style>
<div class="tools">
  <h1>QR cards for reception desks</h1>
  <p>Pick a city, then print (A4, actual size, no margins). Ten cards to a sheet: cut along the dashed lines. Each code opens that city’s free walk.</p>
  <nav class="pick" aria-label="City">{''.join(links)}</nav>
</div>
{''.join(sheets)}
</html>
'''
(ROOT / 'marketing' / 'cards.html').write_text(page)
print(f'Wrote marketing/cards.html: {len(sheets)} cities, links to {SITE}')
