for (const [lang, list] of Object.entries(cases)) {
  test(`numbers in words: ${lang}`, () => {
    for (const [input, expected] of list) assert.equal(spellNumbers(input, lang), expected, `${lang}: ${input}`);
  });
}

test('a whole sentence, and text without numbers, and an unknown language', () => {
  assert.equal(
    spellNumbers('Built in 1904 for 1,200 people, it rises 36 m over the 14th-century square.', 'en'),
    'Built in nineteen oh four for one thousand two hundred people, it rises thirty-six metres over the fourteenth-century square.',
  );
  assert.equal(spellNumbers('No numbers here, nor Roman ones.', 'en'), 'No numbers here, nor Roman ones.');
  assert.equal(spellNumbers('In 1904.', 'xx'), 'In 1904.');
});

test('roman numerals', () => {
  assert.equal(romanToNumber('XIV'), 14);
  assert.equal(romanToNumber('MCMXC'), 1990);
  assert.equal(romanToNumber('IX'), 9);
});
